/* ——— 4e : calcul littéral (révision) ——— */
const litteralIntro = (a: number, b: number) => (p: Passion) => {
  const l = p.lex;
  if (!l.owner) return `Tu as ${b} ${l.unit} au départ et tu en gagnes ${a} par ${l.event}. Après n ${l.events}, tu as ${a}n + ${b} ${l.unit}.`;
  return `${cap(l.owner)} a ${b} ${l.unit} au départ et en ${l.gain === "gagne" ? "gagne" : "obtient"} ${a} par ${l.event}. Après n ${l.events}, ${l.pronoun} a ${a}n + ${b} ${l.unit}.`;
};

